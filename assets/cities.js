// ── CITY CARD TOGGLE ─────────────────────────────────────────
// Called from onclick on each card generated by buildCityCard()
function toggleCity(card) {
  const detail  = card.querySelector('.city-detail');
  const wasOpen = detail.classList.contains('open');
  document.querySelectorAll('.city-detail').forEach(x => x.classList.remove('open'));
  document.querySelectorAll('.city-card').forEach(c => c.style.borderColor = '');
  if (!wasOpen) {
    detail.classList.add('open');
    card.style.borderColor = 'var(--accent)';
  }
}

// ── LIGHTBOX STATE ────────────────────────────────────────────
// Module-level — shared across all city cards
let _lbPhotos  = [];   // current city's photos array
let _lbIndex   = 0;    // which photo is showing

function openLightbox(photos, startIndex) {
  _lbPhotos = photos;
  _lbIndex  = startIndex;

  const lb = document.getElementById('lightbox');
  // Toggle single-photo mode (hides arrows + counter)
  lb.classList.toggle('single', photos.length === 1);
  lb.classList.add('open');
  document.body.style.overflow = 'hidden';

  _lbRender();
}

function _lbRender() {
  const photo = _lbPhotos[_lbIndex];
  const img   = document.getElementById('lb-img');

  // Fade swap: hide → update src → show
  img.style.animation = 'none';
  img.offsetHeight;                        // force reflow
  img.style.animation = '';

  img.src = photo.src;
  img.alt = photo.alt;
  document.getElementById('lb-caption').textContent = photo.alt;
  document.getElementById('lb-counter').textContent =
    _lbPhotos.length > 1 ? `${_lbIndex + 1} / ${_lbPhotos.length}` : '';
}

function navigateLightbox(dir) {
  _lbIndex = (_lbIndex + dir + _lbPhotos.length) % _lbPhotos.length;
  _lbRender();
}

function closeLightbox() {
  document.getElementById('lightbox').classList.remove('open');
  document.body.style.overflow = '';
  _lbPhotos = [];
  _lbIndex  = 0;
}

// Keyboard support — arrow keys + ESC
document.addEventListener('keydown', e => {
  const lb = document.getElementById('lightbox');
  if (!lb.classList.contains('open')) return;
  if (e.key === 'ArrowLeft')  navigateLightbox(-1);
  if (e.key === 'ArrowRight') navigateLightbox(1);
  if (e.key === 'Escape')     closeLightbox();
});

// Click backdrop (the dark area outside the image) to close
// Guard against lightbox not yet in DOM
const _lb = document.getElementById('lightbox');
if (_lb) {
  _lb.addEventListener('click', e => {
    if (e.target.id === 'lightbox') closeLightbox();
  });
}

// ── TOUCH / SWIPE SUPPORT ────────────────────────────────────
(function () {
  let touchStartX = 0;
  const lb = document.getElementById('lightbox');
  if (!lb) return;
  lb.addEventListener('touchstart', e => { touchStartX = e.touches[0].clientX; }, { passive: true });
  lb.addEventListener('touchend',   e => {
    const dx = e.changedTouches[0].clientX - touchStartX;
    if (Math.abs(dx) > 50) navigateLightbox(dx < 0 ? 1 : -1);
  }, { passive: true });
})();

// ── PHOTO STRIP ───────────────────────────────────────────────
function buildPhotoStrip(photos) {
  if (!photos || photos.length === 0) return '';

  // Serialize the photos array once so each img can reference it
  const photosJSON = JSON.stringify(photos).replace(/'/g, '&#39;').replace(/"/g, '&quot;');

  const items = photos.map((p, i) => `
    <img
      src="${p.src}"
      alt="${p.alt}"
      loading="lazy"
      title="${p.alt}"
      style="width:100px;height:70px;object-fit:cover;border-radius:6px;
             flex-shrink:0;border:1px solid var(--border);
             cursor:pointer;transition:opacity .2s,transform .2s"
      onmouseover="this.style.opacity='.82';this.style.transform='scale(1.04)'"
      onmouseout="this.style.opacity='1';this.style.transform='scale(1)'"
      onclick="event.stopPropagation();openLightbox(${photosJSON},${i})"
      onerror="this.style.display='none'"
    >`).join('');

  return `<div class="city-photos" style="display:flex;gap:6px;overflow-x:auto;
    margin-bottom:12px;padding-bottom:4px;-webkit-overflow-scrolling:touch">
    ${items}
  </div>`;
}

function buildCityCard(city) {
  const tagsHTML = city.tags
    .map(tag => `<span class="city-tag">${tag}</span>`)
    .join('');

  const attractionsHTML = city.attractions
    .map((item, i) => `
      <li><span class="attr-n">${i + 1}</span>${item}</li>`)
    .join('');

  const photoStrip = buildPhotoStrip(city.photos);

  return `
    <div class="city-card" onclick="toggleCity(this)">
      <div class="city-card-top">
        <div class="city-emoji-big">${city.emoji}</div>
        <div class="city-difficulty">
          <div class="diff-label">Difficulty</div>
          <div class="diff-stars">${city.difficulty}</div>
        </div>
      </div>
      <div class="city-name-zh">${city.nameZh}</div>
      <div class="city-name-en">${city.nameEn}</div>
      <div class="city-days">🗓 ${city.days}</div>
      <div class="city-best-for"><strong>Best for:</strong> ${city.bestFor}</div>
      <div class="city-tags">${tagsHTML}</div>
      <div class="city-detail">
        ${photoStrip}
        <div class="city-must-see">Top 10 Must-See</div>
        <ol class="attr-list">${attractionsHTML}</ol>
      </div>
    </div>`;
}

async function loadCities() {
  const container = document.getElementById('cities-container');
  if (!container) return;

  try {
    const response = await fetch('./data/cities.json');
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const cities = await response.json();
    container.innerHTML = cities.map(buildCityCard).join('');
  } catch (err) {
    console.error('loadCities() failed:', err);
    container.innerHTML = `<p style="color:var(--text-muted);font-size:13px;padding:20px 0">
      City guide is loading... if this persists, please refresh. 🔄</p>`;
  }
}

loadCities();
